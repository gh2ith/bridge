'use strict';

const fs = require('node:fs');
const path = require('node:path');
const model = require('../docs/database/database-data.js');

function buildSubmission(databaseName = 'Bridgeway_Submission_v2') {
  if (!/^Bridgeway_(Submission_v2|Validation_[A-Za-z0-9_]+)$/.test(databaseName) || databaseName.length > 128) {
    throw new Error('Use Bridgeway_Submission_v2 or a uniquely named Bridgeway_Validation_ database.');
  }

  const foreignKeys = model.tables.reduce((total, table) => total + table.foreignKeys.length, 0);
  const quoteLiteral = text => "N'" + text.replaceAll("'", "''") + "'";
  const schema = model.ddl();
  const verification = `IF (SELECT COUNT(*) FROM sys.tables WHERE is_ms_shipped = 0) <> ${model.tables.length}
    THROW 51491, 'The installed table count differs from the revised schema.', 1;
IF (SELECT COUNT(*) FROM sys.foreign_keys WHERE is_ms_shipped = 0) <> ${foreignKeys}
    THROW 51492, 'The installed foreign key count differs from the revised schema.', 1;`;
  const result = `SELECT DB_NAME() AS InstalledDatabase,
       (SELECT COUNT(*) FROM sys.tables WHERE is_ms_shipped = 0) AS UserTableCount,
       (SELECT COUNT(*) FROM sys.foreign_keys WHERE is_ms_shipped = 0) AS ForeignKeyCount;`;
  const queries = model.queries.map(query => `/*
${query.title}
${query.description}

Select [${databaseName}] in SSMS. Run this query separately.

${query.sql}
*/`).join('\n\n');

  return `-- Bridgeway revised database submission, model ${model.version}.
-- SQL Server 2025 (17.x), compatibility level 170. Run the entire file in SSMS.
-- Generated by node tools/build-database-submission.cjs from docs/database/database-data.js.
-- ${model.tables.length} tables, ${foreignKeys} foreign keys, ${model.queries.length} read query examples.
-- Includes tables, keys, checks and indexes. Workflow write procedures require adaptation.
-- Existing target databases are skipped. A failed installation can leave a new empty database.
USE [master];
GO
SET NOCOUNT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET ARITHABORT ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET NUMERIC_ROUNDABORT OFF;
SET XACT_ABORT ON;

IF TRY_CONVERT(int, SERVERPROPERTY('ProductMajorVersion')) < 17
    THROW 51490, 'Bridgeway requires SQL Server 2025 (17.x) or later.', 1;

IF DB_ID(N'${databaseName}') IS NOT NULL
BEGIN
    PRINT N'${databaseName} already exists. Installation skipped. Choose a new target for a fresh installation.';
    RETURN;
END;

EXEC(N'CREATE DATABASE [${databaseName}];');

BEGIN TRY
    EXEC(N'ALTER DATABASE [${databaseName}] SET COMPATIBILITY_LEVEL = 170;');
    BEGIN TRANSACTION;

    EXEC [${databaseName}].sys.sp_executesql ${quoteLiteral(schema)};

    EXEC [${databaseName}].sys.sp_executesql ${quoteLiteral(verification)};
    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;

EXEC [${databaseName}].sys.sp_executesql ${quoteLiteral(result)};

-- Read query examples. Parameterized examples use NULL until you supply an ID.
-- These statements are comments so installation creates an empty schema.

${queries}
`;
}

if (require.main === module) {
  const target = path.resolve(__dirname, '../database/submission/Bridgeway-FULL-Database.sql');
  fs.writeFileSync(target, buildSubmission(), 'utf8');
  console.log(`Generated ${model.tables.length}-table submission from model ${model.version}.`);
}

module.exports = { buildSubmission };
